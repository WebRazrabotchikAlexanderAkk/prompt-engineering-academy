import { test, expect } from '@playwright/test';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('готовая сборка в подпапке: страницы, ресурсы, сохранение и тест', async ({ page, baseURL }) => {
  const errors: string[] = [];
  const failed: string[] = [];
  const escaped: string[] = [];
  const origin = new URL(baseURL!).origin;
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => failed.push(`${request.url()}: ${request.failure()?.errorText}`));
  page.on('response', response => { if (response.status() >= 400) failed.push(`${response.status()} ${response.url()}`); });
  page.on('request', request => {
    const url = new URL(request.url());
    if (url.origin === origin && !url.pathname.startsWith('/acceptance-preview/')) escaped.push(url.pathname);
  });
  await page.goto('./');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Управляйте AI осознанно');
  await expect(page.locator('astro-dev-toolbar')).toHaveCount(0);
  await page.screenshot({ path: join(tmpdir(), 'pea-static-home-dark.png') });
  await page.setViewportSize({ width: 360, height: 900 });
  await page.screenshot({ path: join(tmpdir(), 'pea-static-home-dark-mobile.png') });
  await page.setViewportSize({ width: 1280, height: 720 });
  await expect(page.locator('link[rel="icon"]')).toHaveAttribute('href', '/acceptance-preview/favicon.svg');
  const icon = await page.request.get(new URL('favicon.svg', baseURL).href);
  expect(icon.status()).toBe(200);
  expect(icon.headers()['content-type']).toContain('image/svg+xml');
  const links = await page.locator('#missions ol a').evaluateAll(elements => elements.map(element => (element as HTMLAnchorElement).href));
  expect(links).toHaveLength(6);
  for (const url of [...links, new URL('about/', baseURL).href]) {
    expect(url).toContain('/acceptance-preview/');
    const response = await page.goto(url);
    expect(response?.status()).toBe(200);
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
  }
  await page.goto('./');
  await page.getByRole('button', { name: 'Светлая', exact: true }).click();
  await page.screenshot({ path: join(tmpdir(), 'pea-static-home-light.png') });
  await page.getByRole('link', { name: 'Начать обучение', exact: true }).click();
  await expect(page).toHaveURL(/\/acceptance-preview\/articles\/how-llms-work\/$/);
  await page.screenshot({ path: join(tmpdir(), 'pea-static-article.png') });
  const exercise = page.locator('[data-exercise-type="TrueFalse"]');
  await exercise.scrollIntoViewIfNeeded();
  await exercise.getByRole('radio', { name: 'Верно', exact: true }).check();
  await exercise.getByRole('button', { name: 'Проверить ответ' }).click();
  await expect(exercise.getByText('Пока неверно', { exact: false })).toBeVisible();
  await exercise.getByRole('radio', { name: 'Неверно', exact: true }).check();
  await exercise.getByRole('button', { name: 'Отправить окончательный ответ' }).click();
  await page.reload();
  await exercise.scrollIntoViewIfNeeded();
  await expect(exercise.getByText('Первый результат:', { exact: false })).toHaveText('Первый результат: 0%. Окончательный: 100%.');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.screenshot({ path: join(tmpdir(), 'pea-static-exercise.png') });
  await page.getByRole('link', { name: 'Итоговый тест', exact: true }).click();
  await expect(page).toHaveURL(/\/acceptance-preview\/quiz\/$/);
  await page.getByRole('button', { name: 'Начать тест', exact: true }).click();
  await page.screenshot({ path: join(tmpdir(), 'pea-static-quiz-question.png') });
  for (let index = 0; index < 12; index++) await page.getByRole('button', { name: 'Пропустить вопрос', exact: true }).click();
  await expect(page.getByText('Исправлено 0 из 12', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Завершить без остальных исправлений' }).click();
  await expect(page.getByRole('heading', { name: 'Итоговый результат' })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Первичный результат', { exact: false }).first()).toContainText('0%');
  await expect(page.getByText('Финальный результат', { exact: false }).first()).toContainText('0%');
  await page.getByRole('heading', { name: 'Итоговый результат' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: join(tmpdir(), 'pea-static-final.png') });
  const recommendation = page.getByRole('link', { name: 'Как работают LLM', exact: true });
  await expect(recommendation).toHaveAttribute('href', '/acceptance-preview/articles/how-llms-work/');
  await recommendation.click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Как работают LLM');
  expect(escaped).toEqual([]);
  expect(failed).toEqual([]);
  expect(errors).toEqual([]);
});
